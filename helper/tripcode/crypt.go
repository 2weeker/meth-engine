func Crypt(key []byte, salt string) string {
	block := cryptBlock(key, salt)
	out := make([]byte, 0, 13)
	out = append(out, salt[0], salt[1])
	for i := range 11 {
		v := 0
		for j := range 6 {
			v <<= 1
			if k := i*6 + j; k < 64 {
				v |= int(block[k])
			}
		}
		out = append(out, alphabet[v])
	}
	return string(out)
}

func cryptBlock(key []byte, salt string) [64]byte {
	var kbits [64]byte
	for i := 0; i < 8 && i < len(key) && key[i] != 0; i++ {
		c := key[i] << 1
		for j := range 8 {
			kbits[i*8+j] = (c >> (7 - j)) & 1
		}
	}
	subkeys := schedule(kbits)

	e := expansion
	for i := range 2 {
		v := saltValue(salt[i])
		for j := range 6 {
			if (v>>j)&1 == 1 {
				e[6*i+j], e[6*i+j+24] = e[6*i+j+24], e[6*i+j]
			}
		}
	}

	var block [64]byte
	for range 25 {
		block = encrypt(block, &subkeys, &e)
	}
	return block
}

func saltValue(c byte) int {
	v := int(c)
	if v > 'Z' {
		v -= 6
	}
	if v > '9' {
		v -= 7
	}
	return v - '.'
}

func schedule(key [64]byte) (subkeys [16][48]byte) {
	var cd [56]byte
	for i, p := range pc1 {
		cd[i] = key[p-1]
	}
	for r := range 16 {
		for s := 0; s < shifts[r]; s++ {
			c0, d0 := cd[0], cd[28]
			copy(cd[0:27], cd[1:28])
			copy(cd[28:55], cd[29:56])
			cd[27], cd[55] = c0, d0
		}
		for i, p := range pc2 {
			subkeys[r][i] = cd[p-1]
		}
	}
	return subkeys
}

func encrypt(in [64]byte, subkeys *[16][48]byte, e *[48]byte) (out [64]byte) {
	var lr [64]byte
	for i, p := range ip {
		lr[i] = in[p-1]
	}
	var l, r [32]byte
	copy(l[:], lr[:32])
	copy(r[:], lr[32:])
	for round := range 16 {
		var x [48]byte
		for i, p := range e {
			x[i] = r[p-1] ^ subkeys[round][i]
		}
		var f [32]byte
		for b := range 8 {
			s := x[b*6 : b*6+6]
			row := s[0]<<1 | s[5]
			col := s[1]<<3 | s[2]<<2 | s[3]<<1 | s[4]
			v := sboxes[b][row*16+col]
			for j := range 4 {
				f[b*4+j] = (v >> (3 - j)) & 1
			}
		}
		var next [32]byte
		for i, p := range perm {
			next[i] = l[i] ^ f[p-1]
		}
		l, r = r, next
	}
	var pre [64]byte
	copy(pre[:32], r[:])
	copy(pre[32:], l[:])
	for i, p := range fp {
		out[i] = pre[p-1]
	}
	return out
}
